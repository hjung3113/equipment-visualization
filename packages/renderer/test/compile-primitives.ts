import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { sanitizePrimitive } from '../src/sanitize.js';
import type { SvgNode } from '../src/svg.js';
import { glyphBoxOf } from './bounds.js';

export interface GlyphBox {
  x: number; y: number; width: number; height: number;
}

export interface PrimitiveParts {
  body: SvgNode;
  glyph: SvgNode | null;
  rest: SvgNode[];
  viewBox: { x: number; y: number; width: number; height: number };
  stretches: boolean;
  glyphBox: GlyphBox | null;
}

export function readAssets(): Record<string, string> {
  const dir = fileURLToPath(new URL('../../../assets/primitives/', import.meta.url));
  const out: Record<string, string> = {};
  for (const file of readdirSync(dir).filter((name) => name.endsWith('.svg')).sort()) {
    out[file.replace(/\.svg$/, '')] = readFileSync(`${dir}/${file}`, 'utf8');
  }
  return out;
}

function viewBoxOf(value: string | undefined): PrimitiveParts['viewBox'] {
  const parts = (value ?? '').trim().split(/[\s,]+/).map(Number);
  if (parts.length !== 4 || parts.some((n) => !Number.isFinite(n))) throw new Error(`bad viewBox: ${value}`);
  return { x: parts[0]!, y: parts[1]!, width: parts[2]!, height: parts[3]! };
}

export function splitPrimitive(root: SvgNode): PrimitiveParts {
  const elements = root.children.filter((child): child is SvgNode => typeof child !== 'string');
  const title = elements[0];
  const body = elements[1];
  if (!title || title.tag !== 'title' || !body) throw new Error('primitive is missing a title or a body');
  let glyph: SvgNode | null = null;
  const rest: SvgNode[] = [];
  for (const el of elements.slice(2)) {
    if (el.tag === 'g' && el.attrs['data-part'] === 'glyph') glyph = el;
    else rest.push(el);
  }
  return {
    body,
    glyph,
    rest,
    viewBox: viewBoxOf(root.attrs.viewBox),
    stretches: root.attrs.preserveAspectRatio === 'none',
    glyphBox: glyph ? glyphBoxOf(glyph) : null,
  };
}

export function renderPrimitivesModule(assets: Record<string, string>): string {
  const record: Record<string, PrimitiveParts> = {};
  for (const name of Object.keys(assets).sort()) {
    record[name] = splitPrimitive(sanitizePrimitive(assets[name] ?? ''));
  }
  return [
    '// Generated by packages/renderer/test/primitives.test.ts. Regenerate with pnpm --filter @eqv/renderer run gen:primitives.',
    "import type { SvgNode } from './svg.js';",
    '',
    'export interface GlyphBox {',
    '  x: number;',
    '  y: number;',
    '  width: number;',
    '  height: number;',
    '}',
    '',
    'export interface PrimitiveParts {',
    '  body: SvgNode;',
    '  glyph: SvgNode | null;',
    '  rest: SvgNode[];',
    '  viewBox: { x: number; y: number; width: number; height: number };',
    '  stretches: boolean;',
    '  glyphBox: GlyphBox | null;',
    '}',
    '',
    `export const primitives: Record<string, PrimitiveParts> = ${JSON.stringify(record, null, 2)};`,
    '',
  ].join('\n');
}
